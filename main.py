"""
Multi-Doc Router API
====================
FastAPI application that routes questions to the most relevant document
using BGE-M3 embeddings via Ollama, retrieves from ChromaDB, and generates
answers with Llama 3.2.
"""

from __future__ import annotations

from contextlib import asynccontextmanager
from typing import Optional

from fastapi import FastAPI
from pydantic import BaseModel, Field

from graph import run_router_graph, _init_collections


# ---------------------------------------------------------------------------
# Lifespan — warm up models & index docs at startup
# ---------------------------------------------------------------------------

@asynccontextmanager
async def lifespan(app: FastAPI):
    # Pre-index documents into ChromaDB and warm up the embedding model
    _init_collections()
    yield


# ---------------------------------------------------------------------------
# FastAPI app
# ---------------------------------------------------------------------------

app = FastAPI(
    title="Multi-Doc Router API",
    description=(
        "An API that takes a question, automatically routes it to the most "
        "relevant document out of 3 sample documents, and answers from that "
        "document — with an explanation of why it was chosen.\n\n"
        "**Stack:** FastAPI + LangGraph + Ollama (BGE-M3 embeddings, Llama 3.2 generation) + ChromaDB\n\n"
        "**Documents:**\n"
        "1. 🌿 Photosynthesis in Plants\n"
        "2. 🕳️ Black Holes and Spacetime\n"
        "3. 🐍 Python Programming Basics\n\n"
        "If the question is ambiguous (matches multiple docs with similar "
        "confidence), the API returns a refusal instead of guessing."
    ),
    version="1.0.0",
    lifespan=lifespan,
)


# ---------------------------------------------------------------------------
# Request / Response models
# ---------------------------------------------------------------------------

class QuestionInput(BaseModel):
    question: str = Field(
        ...,
        description="The question to route and answer.",
        json_schema_extra={"example": "What is the Calvin cycle?"},
    )


class RouterResponse(BaseModel):
    answer: Optional[str] = Field(
        None,
        description="The answer generated by Llama 3.2 from the chosen document, or null if ambiguous.",
    )
    chosen_doc: Optional[str] = Field(
        None,
        description="Title of the document that was selected, or null if ambiguous.",
    )
    reason: str = Field(
        ...,
        description="Explanation of why that document was picked (or why the request was refused).",
    )


# ---------------------------------------------------------------------------
# Endpoints
# ---------------------------------------------------------------------------

@app.post(
    "/ask-router",
    response_model=RouterResponse,
    summary="Route a question to the best-matching document and answer it",
    tags=["Router"],
)
async def ask_router(body: QuestionInput):
    """
    1. Embeds the question using **BGE-M3** via Ollama.
    2. Compares against each document's title/summary embedding (cosine similarity).
    3. If confidence is low or two documents score too closely → refusal response.
    4. Otherwise retrieves the top chunks from **ChromaDB** and generates an
       answer with **Llama 3.2** via Ollama.
    """
    result = run_router_graph(body.question)
    return RouterResponse(**result)


@app.get("/health", tags=["Health"])
async def health():
    """Health-check endpoint."""
    return {"status": "ok"}
